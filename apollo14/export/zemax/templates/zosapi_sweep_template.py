class _Tee:
    """Mirror text writes to multiple streams."""
    def __init__(self, *streams):
        self._streams = streams

    def write(self, data):
        for stream in self._streams:
            stream.write(data)

    def flush(self):
        for stream in self._streams:
            stream.flush()


@contextmanager
def _tee_console(log_path):
    """Mirror stdout/stderr to a log file under the bundle's out directory."""
    log_path = Path(log_path)
    log_path.parent.mkdir(parents=True, exist_ok=True)
    with log_path.open("w", encoding="utf-8") as handle:
        with redirect_stdout(_Tee(sys.stdout, handle)):
            with redirect_stderr(_Tee(sys.stderr, handle)):
                yield


def find_objects(prescription):
    detectors = [entry for entry in prescription["objects"]
                 if entry["type"] == "detector_rectangle"]
    sources = [entry for entry in prescription["objects"]
               if entry["type"] == "source_two_angle"]
    detectors.sort(key=lambda entry: entry["index"])
    sources.sort(key=lambda entry: entry["index"])
    detector_directories = [
        detector_directory_name(entry).casefold() for entry in detectors
    ]
    if len(set(detector_directories)) != len(detector_directories):
        raise RuntimeError(
            "Detector labels do not map to unique output-directory names.")
    return detectors, sources


def _set_first_available_attribute(target, candidates, value):
    """Write the first matching source-power attribute on ``target``."""
    for name in candidates:
        if not hasattr(target, name):
            continue
        try:
            setattr(target, name, value)
            return True
        except Exception:  # noqa: BLE001 - try the next API spelling.
            continue
    return False


def _set_source_parameter(nce_object, ZOSAPI, column_name, value, integer=False):
    """Set one common source parameter through the version-stable NCE cell."""
    try:
        column = getattr(ZOSAPI.Editors.NCE.ObjectColumn, column_name)
        cell = nce_object.GetObjectCell(column)
    except Exception as error:  # noqa: BLE001
        raise RuntimeError(
            f"Could not access source parameter {column_name}: {error!r}.") from error

    attributes = (("IntegerValue", "DoubleValue") if integer
                  else ("DoubleValue", "IntegerValue"))
    errors = []
    for attribute in attributes:
        if not hasattr(cell, attribute):
            continue
        try:
            typed_value = int(value) if attribute == "IntegerValue" else float(value)
            setattr(cell, attribute, typed_value)
            return
        except Exception as error:  # noqa: BLE001
            errors.append(f"{attribute}: {error!r}")
    raise RuntimeError(
        f"Could not set source parameter {column_name} to {value!r}; "
        + "; ".join(errors or ["no writable value property"]))


def _set_source_power(nce_object, ZOSAPI, power):
    """Set common source parameter 3, trying typed data before the cell."""
    object_data = nce_object.ObjectData
    if _set_first_available_attribute(
            object_data, SOURCE_POWER_CANDIDATES, float(power)):
        return
    _set_source_parameter(nce_object, ZOSAPI, "Par3", power)


def _system_wavelength_color_mode(ZOSAPI):
    """Resolve the source color mode used by polychromatic field traces."""
    source_color_mode = ZOSAPI.Editors.NCE.SourceColorMode
    for name in SOURCE_COLOR_ENUM_CANDIDATES:
        if hasattr(source_color_mode, name):
            return getattr(source_color_mode, name)
    raise RuntimeError(
        "This OpticStudio ZOS-API has no System Wavelengths source-color enum. "
        "The position-space sweep cannot configure polychromatic traces.")


def configure_sources_for_polychromatic_trace(editor, sources, ZOSAPI):
    """Use System Wavelengths with parameter 4 = 0 on every field source."""
    mode = _system_wavelength_color_mode(ZOSAPI)
    for entry in sources:
        nce_object = editor.GetObjectAt(entry["index"])
        try:
            sources_data = nce_object.SourcesData
            if (hasattr(sources_data, "IsSourcesAvailable")
                    and not sources_data.IsSourcesAvailable):
                raise RuntimeError("SourcesData is unavailable for this object.")
            sources_data.SourceColor = mode
        except Exception as error:  # noqa: BLE001
            raise RuntimeError(
                f"Could not set source {entry.get('label', entry['index'])!r} "
                f"to System Wavelengths: {error!r}.") from error
        _set_source_parameter(nce_object, ZOSAPI, "Par4", 0, integer=True)


def set_only_active_source(editor, sources, active_index, ZOSAPI):
    """Enable one field source at its analysis power and mute every other source."""
    matching_sources = [
        entry for entry in sources if entry["index"] == active_index
    ]
    if len(matching_sources) != 1:
        raise KeyError(f"Source object {active_index!r} is not unique in the sweep.")

    active_source = matching_sources[0]
    source_data = active_source.get("data", {})
    if not isinstance(source_data, dict):
        raise ValueError(
            f"Source {active_source.get('label', active_index)!r} data must be a mapping.")
    try:
        active_power = float(source_data.get("sweep_power", 1.0))
    except (TypeError, ValueError) as error:
        raise ValueError(
            f"Source {active_source.get('label', active_index)!r} has an invalid "
            "sweep_power.") from error
    if not math.isfinite(active_power) or active_power < 0.0:
        raise ValueError(
            f"Source {active_source.get('label', active_index)!r} has invalid "
            f"sweep_power {active_power!r}.")

    for entry in sources:
        power = active_power if entry is active_source else 0.0
        nce_object = editor.GetObjectAt(entry["index"])
        _set_source_power(nce_object, ZOSAPI, power)


def trace(system):
    """Run one non-sequential ray trace with splitting and polarization on."""
    ray_trace = system.Tools.OpenNSCRayTrace()
    try:
        ray_trace.SplitNSCRays = True
        ray_trace.ScatterNSCRays = False
        ray_trace.UsePolarization = True
        ray_trace.IgnoreErrors = True
        ray_trace.ClearDetectors(0)
        ray_trace.RunAndWaitForCompletion()
    finally:
        ray_trace.Close()


def _read_detector_with_nce(system, detector_index, pixels_x, pixels_y):
    """Read detector pixels directly from the NSC editor."""
    editor = system.NCE

    values = []
    for pixel in range(1, pixels_x * pixels_y + 1):
        result = editor.GetDetectorData(detector_index, pixel, 0)
        # pythonnet surfaces the out-parameter either as a tuple or a value.
        if isinstance(result, tuple):
            if len(result) < 2 or not result[0]:
                raise RuntimeError(
                    f"NCE.GetDetectorData rejected detector {detector_index}, "
                    f"pixel {pixel}: {result!r}.")
            result = result[1]
        values.append(float(result))
    return [values[row * pixels_x:(row + 1) * pixels_x]
            for row in range(pixels_y)]


def read_detector(system, detector_index, pixels_x, pixels_y):
    """Read documented data type 0: detector flux per pixel."""
    try:
        rows = _read_detector_with_nce(system, detector_index, pixels_x, pixels_y)
        return rows, "NCE.GetDetectorData(data=0: flux per pixel)"
    except Exception as error:  # noqa: BLE001
        raise RuntimeError(
            f"Could not read flux for detector {detector_index} through "
            f"NCE.GetDetectorData(data=0): {error!r}.") from error


def _load_sweep_inputs(prescription_path):
    """Load the prescription JSON used by the sweep runner."""
    with open(prescription_path, encoding="utf-8") as handle:
        return json.load(handle)


def _detector_label(detector):
    """Return the human-readable label for one detector."""
    label = detector.get("comment")
    return label if isinstance(label, str) and label else f"detector_{detector['index']}"


def _detector_output_directory(output_directory, detector):
    """Return the directory that holds one detector's sweep results."""
    return os.path.join(output_directory, detector_directory_name(detector))


def _trace_spectrum(prescription):
    """Return the validated spectrum combined in every field trace."""
    return SystemSpectrum.from_prescription(prescription)


def _relative_path(path, base_directory):
    return os.path.relpath(path, base_directory).replace(os.sep, "/")


def _save_native_detector_data(system, archive, detector, source):
    """Save one just-traced Detector Rectangle state as a native ``.DDR`` file."""
    path = archive.data_path(detector["index"], source["index"])
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        result = system.NCE.SaveDetector(detector["index"], str(path))
    except Exception as error:  # noqa: BLE001
        raise RuntimeError(
            f"Could not save native detector data for "
            f"{_detector_label(detector)!r}, source "
            f"{source.get('label', source['index'])!r}: {error!r}.") from error
    if result is False:
        raise RuntimeError(
            f"OpticStudio rejected native detector-data save for "
            f"{_detector_label(detector)!r}: {path}.")
    if not path.is_file():
        raise RuntimeError(
            f"OpticStudio reported a native detector-data save but did not "
            f"create {path}.")
    archive.record(detector["index"], source["index"], path)
    return path


def _detector_viewer_settings(analysis, ZOSAPI):
    """Return typed Detector Viewer settings across Python.NET generations.

    In Python.NET 3, ``IA_.GetSettings`` is exposed as the base ``IAS_``
    interface. Its Detector Viewer members are only visible after explicitly
    casting it to ``IAS_DetectorViewer``. Older bindings already expose the
    concrete members, so retaining the original object is the compatible
    fallback.
    """
    settings = analysis.GetSettings()
    try:
        detector_viewer_type = (
            ZOSAPI.Analysis.Settings.RayTracing.IAS_DetectorViewer)
    except Exception:  # noqa: BLE001 - old API bindings lack this namespace.
        return settings
    try:
        return detector_viewer_type(settings)
    except Exception:  # noqa: BLE001 - older pythonnet needs no explicit cast.
        try:
            return settings.__implementation__
        except AttributeError:
            return settings


def _write_native_detector_viewer_config(system, ZOSAPI, detector, archive):
    """Write a Detector Viewer config that opens the first native detector map.

    The native archive remains usable if a very old API cannot save analysis
    settings: its ZPL macro then derives a bundle-local False Color Detector
    Viewer config from OpticStudio's stock settings file.
    """
    analyses = getattr(system, "Analyses", None)
    if analyses is None:
        return None

    config_path = archive.archive_directory / "detector_viewer.cfg"
    analysis = None
    try:
        analysis = analyses.New_DetectorViewer()
        settings = _detector_viewer_settings(analysis, ZOSAPI)
        settings.Detector.SetDetectorNumber(detector["index"])
        settings.ShowAs = ZOSAPI.Analysis.DetectorViewerShowAsTypes.FalseColor
        settings.DataType = (
            ZOSAPI.Analysis.DetectorViewerShowDataTypes.IncoherentIrradiance)
        settings.Smoothing = 0
        settings.RayDatabaseFilename = ""
        settings.Filter = ""
        settings.SaveTo(str(config_path))
        if not config_path.is_file():
            raise RuntimeError("SaveTo did not create the settings file.")
        return config_path
    except Exception as error:  # noqa: BLE001
        print(
            "  warning: could not create the preconfigured Detector Viewer "
            f"settings file: {error!r}")
        return None
    finally:
        if analysis is not None:
            try:
                analysis.Close()
            except Exception:  # noqa: BLE001
                pass


def _opticstudio_macro_directory(application):
    """Return OpticStudio's configured ZPL macro directory when available.

    ``ZPLDir`` is the user-configured folder that feeds Programming > Macro
    List.  ``ZemaxDataDir/Macros`` is the documented default and lets the
    generated runner remain compatible with API versions that do not expose
    ``ZPLDir``.
    """
    if application is None:
        return None
    try:
        zpl_directory = getattr(application, "ZPLDir")
    except Exception:  # noqa: BLE001 - API version differences are expected.
        zpl_directory = None
    if zpl_directory:
        return Path(str(zpl_directory))

    try:
        data_directory = getattr(application, "ZemaxDataDir")
    except Exception:  # noqa: BLE001 - API version differences are expected.
        data_directory = None
    if data_directory:
        return Path(str(data_directory)) / "Macros"
    return None


def _install_native_viewer_macro(application, source_path):
    """Install the generated ZPL file where Macro List discovers it.

    The macro itself keeps paths relative to the open ``.zmx`` file, so it can
    live in OpticStudio's macro folder while its matching model and ``.DDR``
    archive remain together in the exported bundle.
    """
    source_path = Path(source_path)
    macro_directory = _opticstudio_macro_directory(application)
    if macro_directory is None:
        print(
            "  warning: could not determine OpticStudio's ZPL folder; "
            f"Macro List entry was not installed. Macro remains: {source_path}")
        return None
    try:
        macro_directory.mkdir(parents=True, exist_ok=True)
        installed_path = macro_directory / source_path.name
        if source_path.resolve() != installed_path.resolve():
            installed_path.write_bytes(source_path.read_bytes())
        try:
            application.UpdateFileLists()
        except Exception:  # noqa: BLE001 - macro file is already installed.
            pass
        print(f"Installed OpticStudio Macro List entry: {installed_path}")
        return installed_path
    except Exception as error:  # noqa: BLE001 - do not discard valid results.
        print(
            "  warning: could not install the OpticStudio Macro List entry: "
            f"{error!r}. Macro remains: {source_path}")
        return None


def _new_detector_outputs(detectors, sources, spectrum, output_directory):
    """Create one response collector and destination per detector."""
    return [
        (
            detector,
            PositionSpaceCube(detector, sources, spectrum),
            _detector_output_directory(output_directory, detector),
        )
        for detector in detectors
    ]


def _capture_field(system, source, detector_outputs, native_archive):
    """Save and read every detector after one completed field trace."""
    readout_route = None
    for detector, cube, _output_directory in detector_outputs:
        native_path = _save_native_detector_data(
            system, native_archive, detector, source)
        pixels_x = detector["data"]["pixels_x"]
        pixels_y = detector["data"]["pixels_y"]
        rows, route = read_detector(
            system, detector["index"], pixels_x, pixels_y)
        cube.record(source["index"], rows)
        if readout_route is None:
            readout_route = route
        total = cube.total_flux(cube.field_index(source["index"]))
        print(
            f"  {cube.detector_label}: total flux {total:.6e} "
            f"[{route}]")
        print(f"    saved native detector data: {native_path}")
    return readout_route


def _trace_metadata(spectrum, readout_route):
    """Describe the invariant settings shared by all field traces."""
    return {
        "source_color": "SystemWavelengths",
        "source_parameter_4": "0 (polychromatic)",
        "system_wavelengths_um": list(spectrum.wavelengths_um),
        "system_wavelength_weights": list(spectrum.weights),
        "ray_splitting": True,
        "scatter_nsc_rays": False,
        "use_polarization": True,
        "clear_detectors": True,
        "detector_readout": readout_route,
    }


def _write_position_space_reports(detector_outputs, output_directory,
                                  trace_metadata):
    """Write every detector's portable field response artifacts."""
    reports = []
    for detector, cube, detector_output_directory in detector_outputs:
        result = cube.write(detector_output_directory, trace_metadata)
        reports.append({
            "detector_label": result["detector_label"],
            "detector_object_index": result["detector_index"],
            "flux_shape": result["shape"],
            "npz": _relative_path(result["npz"], output_directory),
            "metadata": _relative_path(result["metadata"], output_directory),
            "summary": _relative_path(result["summary"], output_directory),
            "html": _relative_path(result["html"], output_directory),
        })
        print(
            f"  wrote {result['detector_label']} response cube: "
            f"{result['html']}")
    return reports


def _write_pupil_reports(detector_outputs, report_specs, output_directory):
    """Write configured cross-field reports from completed Zemax cubes."""
    if not report_specs:
        return []
    results = write_configured_pupil_reports(
        [cube for _detector, cube, _directory in detector_outputs],
        report_specs,
        output_directory,
    )
    reports = []
    for result in results:
        reports.append({
            "report_name": result["report_name"],
            "title": result["title"],
            "detector_label": result["detector_label"],
            "html": _relative_path(result["html"], output_directory),
            "json": _relative_path(result["json"], output_directory),
            "cell_summary_csv": _relative_path(
                result["cell_summary_csv"], output_directory),
            "field_summary_csv": _relative_path(
                result["field_summary_csv"], output_directory),
        })
        print(f"  wrote Zemax-derived pupil/FOV report: {result['html']}")
        for related in result.get("related_reports", []):
            record = {
                "report_name": related["report_name"],
                "title": related["title"],
                "detail": related["detail"],
                "detector_label": related["detector_label"],
                "html": _relative_path(related["html"], output_directory),
            }
            if related.get("csv"):
                record["csv"] = _relative_path(
                    related["csv"], output_directory)
            reports.append(record)
            print(f"  wrote Zemax-derived angular response: {related['html']}")
    return reports


def _finalize_native_archive(system, ZOSAPI, application, detectors,
                             native_archive, output_directory):
    """Write, install, and index the native Detector Viewer artifacts."""
    viewer_config = _write_native_detector_viewer_config(
        system, ZOSAPI, detectors[0], native_archive)
    native_result = native_archive.write(viewer_config)
    installed_macro = _install_native_viewer_macro(
        application, native_result["macro"])
    native_index = {
        "archive": _relative_path(native_result["manifest"], output_directory),
        "macro": _relative_path(native_result["macro"], output_directory),
        "macro_list_entry": (
            None if installed_macro is None else str(installed_macro)),
        "records": native_result["records"],
        "detector_viewer_settings": (
            None if native_result["viewer_config"] is None else _relative_path(
                native_result["viewer_config"], output_directory)),
    }
    return native_result, native_index


def _run_position_space_sweep(system, ZOSAPI, sources, detectors, spectrum,
                              output_directory, model_directory=None,
                              application=None, pupil_report_specs=None,
                              coating_report=None):
    """Trace each field once with its complete system-wavelength spectrum."""
    if not sources:
        raise RuntimeError("The prescription contains no source_two_angle objects.")
    if not detectors:
        raise RuntimeError("The prescription contains no detector_rectangle objects.")

    output_directory = Path(output_directory)
    model_directory = Path(
        output_directory.parent if model_directory is None else model_directory)
    native_archive = NativeDetectorArchive(
        output_directory, model_directory, sources, detectors, spectrum)
    detector_outputs = _new_detector_outputs(
        detectors, sources, spectrum, output_directory)

    configure_sources_for_polychromatic_trace(system.NCE, sources, ZOSAPI)
    readout_route = None
    for trace_number, source in enumerate(sources, start=1):
        label = source.get("label", f"source_{source['index']}")
        set_only_active_source(system.NCE, sources, source["index"], ZOSAPI)
        print(
            f"[{trace_number}/{len(sources)}] {label}, polychromatic "
            "System Wavelengths (wavenumber 0)")
        trace(system)
        route = _capture_field(
            system, source, detector_outputs, native_archive)
        if readout_route is None:
            readout_route = route

    trace_metadata = _trace_metadata(spectrum, readout_route)
    reports = _write_position_space_reports(
        detector_outputs, output_directory, trace_metadata)
    derived_reports = _write_pupil_reports(
        detector_outputs, pupil_report_specs or [], output_directory)
    coating_index_record = write_coating_report(coating_report, output_directory)
    if coating_index_record is not None:
        derived_reports.append(coating_index_record)
    native_result, native_index = _finalize_native_archive(
        system, ZOSAPI, application, detectors, native_archive,
        output_directory)
    index_path = write_position_space_index(
        output_directory, reports, native_opticstudio=native_index,
        derived_reports=derived_reports)
    print()
    print(f"Position-space index: {index_path}")
    print(f"Position-space reports: {Path(index_path).with_suffix('.html')}")
    print(f"Native OpticStudio detector archive: {native_result['manifest']}")
    print(f"Native OpticStudio viewer macro: {native_result['macro']}")
    return index_path


def main(model_path, prescription_path, output_directory):
    ZOSAPI, application, system = connect()
    try:
        prescription = _load_sweep_inputs(prescription_path)
        detectors, sources = find_objects(prescription)
        spectrum = _trace_spectrum(prescription)

        system.LoadFile(model_path, False)
        os.makedirs(output_directory, exist_ok=True)
        print(
            f"Tracing {len(sources)} field sources once with "
            f"{len(spectrum.wavelengths_um)} weighted system wavelengths into "
            f"{len(detectors)} detector response cube(s).")
        _run_position_space_sweep(
            system, ZOSAPI, sources, detectors, spectrum, output_directory,
            Path(model_path).resolve().parent, application,
            pupil_report_specs=prescription.get(
                "analyses", {}).get("pupil_reports", []),
            coating_report=prescription.get(
                "analyses", {}).get("coating_report"))
    finally:
        disconnect(application)


if __name__ == "__main__":
    if len(sys.argv) < 3:
        print(__doc__)
        raise SystemExit(1)
    output_argument = os.path.abspath(
        sys.argv[3] if len(sys.argv) > 3 else DEFAULT_OUTPUT_DIRECTORY)
    with _tee_console(Path(output_argument) / "logs" / "run_fov_sweep.log"):
        main(os.path.abspath(sys.argv[1]), os.path.abspath(sys.argv[2]),
             output_argument)
