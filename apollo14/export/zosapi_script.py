def build(prescription_path, output_path):
    ZOSAPI, application, system = connect()
    nce_types = ZOSAPI.Editors.NCE
    prescription, prescription_directory = _load_prescription(prescription_path)
    settings = prescription["system"]
    print("Loaded prescription:")
    print(f"  source: {prescription_path}")
    print(f"  objects: {len(prescription['objects'])}")
    print(f"  wavelengths_um: {settings.get('wavelengths_um')}")
    print(f"  coating_file: {settings.get('coating_file')!r}")
    _print_mirror_coating_plan(prescription)
    _install_coating_file(prescription_directory, settings.get("coating_file"))

    system.New(False)
    system.MakeNonSequential()

    _apply_system_settings(ZOSAPI, system, settings)
    _prime_ray_trace_defaults(system)
    editor = system.NCE
    _populate_objects(ZOSAPI, nce_types, editor, prescription["objects"],
                      prescription_directory)

    system.SaveAs(output_path)
    _print_build_result(output_path)
    disconnect(application)


def _apply_object(ZOSAPI, nce_types, nce_object, entry, base_directory):
    """Type, place and parameterise one non-sequential object."""
    comment = entry["comment"]
    print(
        f"\nApplying object {entry['index']}: {comment} ({entry['type']})")
    print(
        f"  raw coating fields: coating={entry.get('coating')!r}, "
        f"face_coatings={entry.get('face_coatings', {})!r}")
    if entry.get("material"):
        print(f"  material: {entry['material']}")
    if entry.get("inside_of"):
        print(f"  inside_of: {entry['inside_of']}")
    if entry.get("data"):
        print(f"  data keys: {sorted(entry['data'])}")
    object_type = resolve_enum(
        nce_types.ObjectType, OBJECT_TYPE_CANDIDATES[entry["type"]],
        f"object type for {comment}")

    type_settings = nce_object.GetObjectTypeSettings(object_type)
    polygon_file = _resolve_polygon_file(entry, base_directory)
    polygon_file_set = False
    if polygon_file:
        polygon_file_set = _set_polygon_file_on_type_settings(
            type_settings, polygon_file, comment)

    if DEBUG_DUMP_ZOSAPI_MEMBERS and entry["type"] == "polygon":
        _dump_member_inventory(f"{comment}: type settings", type_settings)

    nce_object.ChangeType(type_settings)
    nce_object.Comment = comment
    object_data = getattr(nce_object, "ObjectData", None)

    if polygon_file and not polygon_file_set:
        _set_polygon_file_on_object_data(
            [object_data, nce_object], polygon_file, comment)

    if DEBUG_DUMP_ZOSAPI_MEMBERS and entry["type"] == "polygon":
        _dump_member_inventory(f"{comment}: object row", nce_object)
        _dump_member_inventory_if_present(f"{comment}: object data", object_data)
        _dump_member_inventory_if_present(
            f"{comment}: type data", getattr(nce_object, "TypeData", None))

    _apply_object_pose(nce_object, entry, comment)
    _apply_object_metadata(nce_object, object_data, entry, comment)
    _apply_object_coatings(nce_object, entry, comment)


def _resolve_polygon_file(entry, base_directory):
    """Return the polygon file path, resolved relative to the prescription."""
    polygon_file = entry.get("data", {}).get("polygon_file")
    if not polygon_file:
        return None
    return _resolve_path(base_directory, polygon_file)


def _set_polygon_file_on_type_settings(type_settings, polygon_file, comment):
    """Try the polygon file on the type settings first."""
    # File-backed objects carry their file on the type settings in some
    # OpticStudio versions and on the object data in others, so try both.
    return set_first_available(
        [type_settings],
        POLYGON_FILE_ATTRIBUTE_CANDIDATES,
        polygon_file, f"{comment}: polygon file")


def _set_polygon_file_on_object_data(targets, polygon_file, comment):
    """Try the polygon file on the object data after type settings fail."""
    set_first_available(
        targets,
        POLYGON_FILE_ATTRIBUTE_CANDIDATES,
        polygon_file, f"{comment}: polygon file")


