class _Tee:
    """Mirror text writes to multiple streams."""
    def __init__(self, *streams):
        self._streams = streams

    def write(self, data):
        for stream in self._streams:
            stream.write(data)

    def flush(self):
        for stream in self._streams:
            stream.flush()


@contextmanager
def _tee_console(log_path):
    """Mirror stdout/stderr to a log file under the bundle's out directory."""
    log_path = Path(log_path)
    log_path.parent.mkdir(parents=True, exist_ok=True)
    with log_path.open("w", encoding="utf-8") as handle:
        with redirect_stdout(_Tee(sys.stdout, handle)):
            with redirect_stderr(_Tee(sys.stderr, handle)):
                yield


def _extend_candidates(candidates, *items):
    """Append non-empty path candidates while keeping the call sites compact."""
    for item in items:
        if item:
            candidates.append(item)


def _resolve_path(base_directory, path):
    """Resolve a prescription-relative path against the source file."""
    if os.path.isabs(path):
        return path
    return os.path.abspath(os.path.join(base_directory, path))


def _candidate_paths_from_env_vars():
    """Collect helper DLL candidates from environment variables."""
    candidates = []
    for env_var in NET_HELPER_CANDIDATE_ENV_VARS:
        value = os.environ.get(env_var)
        if not value:
            continue
        if os.path.isdir(value):
            candidates.extend([
                os.path.join(value, NET_HELPER_FILE_NAME),
                os.path.join(value, "ZOS-API", "Libraries",
                             NET_HELPER_FILE_NAME),
                os.path.join(value, "Libraries", NET_HELPER_FILE_NAME),
                os.path.join(value, "bin", NET_HELPER_FILE_NAME),
            ])
            continue
        candidates.append(value)
    return candidates


def _candidate_paths_from_registry():
    """Collect helper DLL candidates from the Windows registry."""
    candidates = []
    if winreg is None:
        return candidates

    registry_hives = (
        winreg.HKEY_CURRENT_USER,
        winreg.HKEY_LOCAL_MACHINE,
    )
    for registry_hive in registry_hives:
        for registry_key, value_names in NET_HELPER_REGISTRY_KEYS:
            try:
                with winreg.OpenKey(registry_hive, registry_key) as key:
                    try:
                        default_value = winreg.QueryValue(key, None)
                    except OSError:
                        default_value = None
                    if default_value:
                        candidates.append(default_value)
                    for value_name in value_names:
                        try:
                            value, _ = winreg.QueryValueEx(key, value_name)
                        except OSError:
                            continue
                        if value:
                            candidates.append(value)
            except OSError:
                continue
    return candidates


def _candidate_paths_from_install_roots():
    """Collect helper DLL candidates from common installation roots."""
    candidates = []
    program_files_roots = [
        os.environ.get("ProgramFiles", r"C:\Program Files"),
        os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)"),
    ]
    for root in program_files_roots:
        if not root:
            continue
        for hint in OPTICSTUDIO_INSTALL_HINTS:
            candidates.append(os.path.join(root, *hint))

    local_appdata = os.environ.get("LOCALAPPDATA")
    if local_appdata:
        _extend_candidates(
            candidates,
            os.path.join(local_appdata, "Programs", "Zemax OpticStudio",
                         "ZOS-API", "Libraries", NET_HELPER_FILE_NAME),
            os.path.join(local_appdata, "Programs", "Ansys Zemax OpticStudio",
                         "ZOS-API", "Libraries", NET_HELPER_FILE_NAME),
        )
    return candidates


def _candidate_paths_from_filesystem_search():
    """Collect helper DLL candidates by scanning common search roots."""
    candidates = []
    search_roots = []
    for root in (
        os.environ.get("ProgramFiles"),
        os.environ.get("ProgramFiles(x86)"),
        os.environ.get("LOCALAPPDATA"),
        str(Path.home()),
    ):
        if root and os.path.isdir(root):
            search_roots.append(root)
    for root in search_roots:
        try:
            for match in Path(root).rglob(NET_HELPER_FILE_NAME):
                candidates.append(str(match))
        except OSError:
            continue
    return candidates


def _candidate_paths_from_drive_scan():
    """Collect helper DLL candidates by scanning mounted drives on Windows."""
    candidates = []
    if os.name != "nt":
        return candidates

    drive_mask = ctypes.windll.kernel32.GetLogicalDrives()
    for drive_index in range(26):
        if not (drive_mask & (1 << drive_index)):
            continue
        drive_root = f"{chr(ord('A') + drive_index)}:\\"
        if os.path.isdir(drive_root):
            try:
                for match in Path(drive_root).rglob(NET_HELPER_FILE_NAME):
                    candidates.append(str(match))
            except OSError:
                continue
    return candidates


def _dedupe_paths(paths):
    """Yield normalized paths once each, preserving first-seen order."""
    seen = set()
    for candidate in paths:
        normalized = os.path.normpath(candidate)
        if normalized in seen:
            continue
        seen.add(normalized)
        yield normalized


def _candidate_net_helper_paths():
    candidates = []
    candidates.extend(_candidate_paths_from_env_vars())
    candidates.extend(_candidate_paths_from_registry())
    candidates.extend(_candidate_paths_from_install_roots())
    candidates.extend(_candidate_paths_from_filesystem_search())
    candidates.extend(_candidate_paths_from_drive_scan())
    yield from _dedupe_paths(candidates)


def _find_net_helper():
    for candidate in _candidate_net_helper_paths():
        if os.path.exists(candidate):
            return candidate
    raise RuntimeError(
        "ZOSAPI_NetHelper.dll not found. Set one of "
        f"{NET_HELPER_CANDIDATE_ENV_VARS!r} to its full path, or add your "
        "OpticStudio install root to the candidate list in this script. "
        "Looked in:\n  " + "\n  ".join(_candidate_net_helper_paths()))


def _load_zosapi_runtime(helper):
    """Load the .NET assemblies required to talk to OpticStudio."""
    clr.AddReference(helper)
    import ZOSAPI_NetHelper

    ZOSAPI_NetHelper.ZOSAPI_Initializer.Initialize()
    zemax_directory = ZOSAPI_NetHelper.ZOSAPI_Initializer.GetZemaxDirectory()
    for dll_name in ZOSAPI_DLL_NAMES:
        clr.AddReference(os.path.join(zemax_directory, dll_name))
    import ZOSAPI
    return ZOSAPI


def _open_application(ZOSAPI):
    """Try a standalone session first, then fall back to an attached one."""
    connection = ZOSAPI.ZOSAPI_Connection()

    application = connection.CreateNewApplication()
    mode = "standalone application"
    if application is None:
        application = connection.ConnectAsExtension(0)
        mode = "interactive extension"
    return application, mode


def _validate_application(application, ZOSAPI):
    """Reject connections that cannot legally use the API."""
    if application is None:
        raise RuntimeError(
            "Could not open OpticStudio. Either no licence seat is free for a "
            "standalone application, or no running instance has Interactive "
            "Extension enabled (Programming → Interactive Extension).")
    print(f"OpticStudio license status: {describe_license(application, ZOSAPI)}")
    if not application.IsValidLicenseForAPI:
        raise RuntimeError(
            "This OpticStudio licence does not permit ZOS-API use. ZOS-API is "
            "included from the Professional edition upward.")


def connect():
    """Open an OpticStudio session and return ``(ZOSAPI, application, system)``.

    Tries a standalone application first, which launches its own headless
    OpticStudio and therefore needs a free licence seat. If none is free —
    typically because OpticStudio is already open on this machine — it falls
    back to attaching to that running instance as an Interactive Extension.
    For the fallback, enable it in OpticStudio under Programming → Interactive
    Extension before running this script.

    Edition requirements: non-sequential mode and ZOS-API are both included from
    the Professional edition upward, and every licence issued from 2023 R1
    onward has non-sequential ray tracing. Only a legacy pre-2023-R1 Standard
    licence, which was sequential-only, cannot run this model at all.
    """
    helper = _find_net_helper()
    ZOSAPI = _load_zosapi_runtime(helper)
    application, mode = _open_application(ZOSAPI)
    _validate_application(application, ZOSAPI)

    global CONNECTION_MODE
    CONNECTION_MODE = mode
    print(f"Connected to OpticStudio ({mode}).")
    return ZOSAPI, application, application.PrimarySystem


def describe_license(application, ZOSAPI):
    """Return a readable license description for the active application."""
    license_status = getattr(application, "LicenseStatus", None)
    if license_status is None:
        return "unknown (no LicenseStatus property)"

    license_type = getattr(ZOSAPI, "LicenseStatusType", None)
    if license_type is not None:
        for name in dir(license_type):
            if name.startswith("_"):
                continue
            try:
                if getattr(license_type, name) == license_status:
                    return f"{name} (raw={license_status!r})"
            except Exception:  # noqa: BLE001
                continue
    return f"{license_status!r}"


CONNECTION_MODE = None


def disconnect(application):
    """Close a standalone session; leave an attached GUI session alone.

    ``CloseApplication`` on an interactive extension would shut down the user's
    own OpticStudio window, so it is only called for a session this script
    started itself.
    """
    if CONNECTION_MODE == "standalone application":
        application.CloseApplication()


def _candidate_coating_folders():
    """Yield likely Zemax coating folders in preference order."""
    candidates = []

    for env_var in COATING_INSTALL_ENV_VARS:
        value = os.environ.get(env_var)
        if value:
            candidates.append(value)

    home = Path.home()
    common_roots = [
        home / "Documents" / "Zemax" / "Coatings",
        home / "OneDrive" / "Documents" / "Zemax" / "Coatings",
        home / "Zemax" / "Coatings",
    ]
    for root in common_roots:
        candidates.append(str(root))

    for root_name in ("ProgramData", "LOCALAPPDATA"):
        root = os.environ.get(root_name)
        if root:
            candidates.append(os.path.join(root, "Zemax", "Coatings"))

    search_roots = [home]
    for root_name in ("ProgramData", "LOCALAPPDATA"):
        root = os.environ.get(root_name)
        if root:
            search_roots.append(Path(root))

    for search_root in search_roots:
        if not search_root.exists():
            continue
        try:
            for match in search_root.rglob("COATING.DAT"):
                candidates.append(str(match.parent))
        except OSError:
            continue

    seen = set()
    for candidate in candidates:
        normalized = os.path.normpath(candidate)
        if normalized in seen:
            continue
        seen.add(normalized)
        yield normalized


def _find_zemax_coating_folder():
    """Return the configured Zemax coating folder, falling back to defaults."""
    for candidate in _candidate_coating_folders():
        if os.path.isdir(candidate):
            return candidate
    return os.path.join(str(Path.home()), "Documents", "Zemax", "Coatings")


def _install_coating_file(source_directory, coating_file):
    """Copy the exported coating file into the machine's Zemax coating folder."""
    if not coating_file:
        return

    source_candidates = [
        os.path.join(source_directory, coating_file),
        os.path.join(source_directory, "Coatings", coating_file),
    ]
    source_path = next((path for path in source_candidates
                        if os.path.exists(path)), None)
    if source_path is None:
        raise FileNotFoundError(
            f"Could not find coating file {coating_file!r} next to the "
            f"prescription in {source_directory!r}.")

    coating_folder = _find_zemax_coating_folder()
    os.makedirs(coating_folder, exist_ok=True)
    target_path = os.path.join(coating_folder, coating_file)

    if os.path.abspath(source_path) == os.path.abspath(target_path):
        return

    shutil.copy2(source_path, target_path)
    print(f"Installed coating file to {target_path}")


# ── Tolerant configuration helpers ──────────────────────────────────────────
# ZOS-API renames properties and enum members between releases. Rather than
# hard-code one spelling and fail, everything uncertain is attempted by name
# against a candidate list, and whatever cannot be applied is reported at the
# end for manual follow-up.

DEFERRED_TO_USER = []


def configure(description, action):
    """Run ``action``; on failure record it instead of aborting the build."""
    try:
        action()
        return True
    except Exception as error:                       # noqa: BLE001
        DEFERRED_TO_USER.append(f"{description}  ({type(error).__name__}: {error})")
        return False


def resolve_enum(enum_container, candidates, what):
    """Return the first enum member present under any candidate name."""
    for name in candidates:
        member = getattr(enum_container, name, None)
        if member is not None:
            return member
    available = [name for name in dir(enum_container)
                 if not name.startswith("_")]
    raise AttributeError(
        f"None of {candidates} is a valid {what}. Available names include: "
        + ", ".join(sorted(available)[:40]))


def _normalized_name(name):
    return "".join(character for character in name.lower()
                   if character.isalnum())


def _set_attributes(target, assignments):
    """Set a compact group of attributes on one object."""
    for name, value in assignments.items():
        setattr(target, name, value)


def _iter_targets(targets):
    for target in targets:
        if target is not None:
            yield target


def _writable_target(target):
    implementation = getattr(target, "__implementation__", None)
    return implementation if implementation is not None else target


def _available_attribute_names(target):
    """Collect attribute names exposed by pythonnet and the runtime type."""
    available = [name for name in dir(target) if not name.startswith("_")]

    # pythonnet sometimes hides CLR properties from ``dir`` even though they
    # are settable through the wrapped .NET type. Probe the runtime type as a
    # second source of truth before giving up.
    try:
        runtime_type = target.GetType()
    except Exception:  # noqa: BLE001
        runtime_type = None
    if runtime_type is not None:
        for property_info in runtime_type.GetProperties():
            if property_info.Name not in available:
                available.append(property_info.Name)
        for field_info in runtime_type.GetFields():
            if field_info.Name not in available:
                available.append(field_info.Name)
    return available


def _match_attribute_exact(available, candidates):
    """Return the first exact attribute match."""
    for candidate in candidates:
        if candidate in available:
            return candidate
    return None


def _match_attribute_normalized(available, candidates):
    """Return the first attribute match after normalization."""
    normalized_available = {
        name: _normalized_name(name) for name in available
    }
    for candidate in candidates:
        normalized_candidate = _normalized_name(candidate)
        for name, normalized_name in normalized_available.items():
            if normalized_name == normalized_candidate:
                return name
    return None


def _match_attribute_substring(available, candidates):
    """Return a unique fuzzy match when one attribute is obviously intended."""
    normalized_available = {
        name: _normalized_name(name) for name in available
    }
    for candidate in candidates:
        normalized_candidate = _normalized_name(candidate)
        matches = [
            name for name, normalized_name in normalized_available.items()
            if normalized_candidate in normalized_name
            or normalized_name in normalized_candidate
        ]
        if len(matches) == 1:
            return matches[0]
    return None


def _resolve_attribute_name(target, candidates):
    """Find the first matching attribute name on ``target``.

    ZOS-API wrappers do not always expose the same casing or suffixes across
    releases, so we first try exact names, then case-insensitive / normalized
    matches, and finally unique substring matches.
    """
    available = _available_attribute_names(target)
    return (
        _match_attribute_exact(available, candidates)
        or _match_attribute_normalized(available, candidates)
        or _match_attribute_substring(available, candidates)
    )


def _search_target_for_available_attribute(target, candidates, value, path,
                                           searched, visited):
    """Search one target and its nested data objects for a writable attribute."""
    writable = _writable_target(target)
    target_id = id(writable)
    if target_id in visited:
        return False
    visited.add(target_id)

    type_name = type(writable).__name__
    searched.append(f"{path}<{type_name}>")

    attribute_name = _resolve_attribute_name(writable, candidates)
    if attribute_name is not None:
        setattr(writable, attribute_name, value)
        searched.append(f"{path}.{attribute_name}")
        return True

    method_name = _try_invoke_string_method(writable, value)
    if method_name is not None:
        searched.append(f"{path}.{method_name}()")
        return True

    for child_name, child in _iter_nested_targets(writable):
        if _search_target_for_available_attribute(child, candidates, value,
                                                 f"{path}.{child_name}",
                                                 searched, visited):
            return True
    return False


def _missing_attribute_note(description, candidates, searched, value):
    """Build the manual-follow-up note for a missing attribute."""
    return (
        f"{description}: none of {candidates} exists on "
        f"{', '.join(searched) or 'no targets'}; set it by hand "
        f"(value {value!r})")


def set_first_available(targets, candidates, value, description):
    """Assign ``value`` to the first matching attribute across ``targets``."""
    searched = []
    visited = set()

    def search(target, path):
        return _search_target_for_available_attribute(
            target, candidates, value, path, searched, visited)

    for index, target in enumerate(_iter_targets(targets), start=1):
        if search(target, f"target{index}"):
            return True

    DEFERRED_TO_USER.append(
        _missing_attribute_note(description, candidates, searched, value))
    return False


