def _load_prescription(prescription_path):
    """Load the exported prescription JSON and its source directory."""
    with open(prescription_path) as handle:
        prescription = json.load(handle)
    prescription_directory = os.path.dirname(os.path.abspath(prescription_path))
    return prescription, prescription_directory


def _print_mirror_coating_plan(prescription):
    """Print the mirror coating mapping before any OpticStudio writes."""
    print("\nMirror coating plan:")
    mirrors = [entry for entry in prescription["objects"]
               if entry.get("comment", "").startswith("mirror_")]
    if not mirrors:
        print("  (no mirror objects found)")
        return

    for entry in mirrors:
        coating = entry.get("coating")
        face_coatings = entry.get("face_coatings", {})
        visible_coating = coating or _visible_face_coating(face_coatings)
        reference = entry.get("reference_reflectance", {})
        wavelengths = reference.get("wavelengths_nm", [])
        values = reference.get("values", [])
        if values:
            reflectance_text = f"{min(values):.4f}..{max(values):.4f}"
        else:
            reflectance_text = "n/a"
        print(
            f"  {entry['comment']}: type={entry.get('type')}, "
            f"coating={visible_coating!r}, raw_coating={coating!r}, "
            f"face_coatings={face_coatings!r}, "
            f"reference_samples={len(wavelengths)}, R={reflectance_text}")


def _visible_face_coating(face_coatings):
    """Show the first face coating when the object-level field is empty."""
    if not face_coatings:
        return None
    if len(face_coatings) == 1:
        return next(iter(face_coatings.values()))
    face_number, face_coating = next(iter(sorted(
        face_coatings.items(), key=lambda item: int(item[0]))))
    return f"face {face_number}: {face_coating}"


def _apply_system_settings(ZOSAPI, system, settings):
    """Apply the system-wide settings from the prescription."""
    configure("lens units → millimetres", lambda: setattr(
        system.SystemData.Units, "LensUnits",
        resolve_enum(ZOSAPI.SystemData.ZemaxSystemUnits, ["Millimeters"],
                     "lens unit")))

    glass_catalog = settings.get("glass_catalog")
    if glass_catalog:
        configure(
            f"add glass catalog {glass_catalog}",
            lambda: system.SystemData.MaterialCatalogs.AddCatalog(glass_catalog))

    coating_file = settings.get("coating_file")
    if coating_file:
        print(f"Selected coating file: {coating_file}")
        def apply_coating_file():
            system.SystemData.Files.CoatingFile = coating_file
            system.SystemData.Files.ReloadFiles()

        configure(f"select coating file {coating_file}", apply_coating_file)

    def apply_wavelengths():
        wavelength_data = system.SystemData.Wavelengths
        while wavelength_data.NumberOfWavelengths > 1:
            wavelength_data.RemoveWavelength(wavelength_data.NumberOfWavelengths)
        wavelength_data.GetWavelength(1).Wavelength = settings["wavelengths_um"][0]
        for value in settings["wavelengths_um"][1:]:
            wavelength_data.AddWavelength(value, 1.0)

    configure("system wavelengths", apply_wavelengths)

    def apply_nonsequential_limits():
        nonsequential = system.SystemData.NonSequentialData
        nonsequential.MaximumSegmentsPerRay = settings["max_segments"]
        nonsequential.MaximumIntersectionsPerRay = settings["max_intersections"]

        def _set_first_available_attribute(target, candidates, value):
            for name in candidates:
                if hasattr(target, name):
                    setattr(target, name, value)
                    return True
            return False

        def _set_setting(candidates, value, label):
            if not _set_first_available_attribute(
                    nonsequential, candidates, value):
                raise AttributeError(
                    f"No OpticStudio property matched {label}.")

        _set_setting(
            ("MaximumNestedTouchingObjects",
             "MaximumNestedAndTouchingObjects"),
            settings["max_nested_touching_objects"],
            "Maximum Nested/Touching Objects")
        _set_setting(
            ("MinimumRelativeRayIntensity", "MinimumRelativeIntensity"),
            settings["min_relative_intensity"],
            "Minimum Relative Ray Intensity")
        _set_setting(
            ("MinimumAbsoluteRayIntensity", "MinimumAbsoluteIntensity"),
            settings["min_absolute_intensity"],
            "Minimum Absolute Ray Intensity")

    configure(
        "ray-splitting limits (max segments / intersections / nested objects / "
        "minimum relative / minimum absolute intensity) — a cascade of partial "
        "mirrors needs these well above stock",
        apply_nonsequential_limits)


def _prime_ray_trace_defaults(system):
    """Set the NSC ray-trace defaults that should survive into the saved model."""
    ray_trace = system.Tools.OpenNSCRayTrace()
    ray_trace.SplitNSCRays = True
    ray_trace.UsePolarization = True
    ray_trace.Close()


def _populate_objects(ZOSAPI, nce_types, editor, objects, prescription_directory):
    """Create and configure every exported object in order."""
    for entry in objects:
        index = entry["index"]
        while editor.NumberOfObjects < index:
            editor.InsertNewObjectAt(editor.NumberOfObjects + 1)
        nce_object = editor.GetObjectAt(index)
        _apply_object(ZOSAPI, nce_types, nce_object, entry,
                      prescription_directory)


