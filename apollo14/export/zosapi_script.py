def set_only_active_source(editor, sources, active_index):
    """Give one source all the power and mute the rest."""
    for entry in sources:
        nce_object = editor.GetObjectAt(entry["index"])
        object_data = nce_object.ObjectData
        power = entry["data"]["power"] if entry["index"] == active_index else 0.0
        _set_first_available_attribute(object_data, SOURCE_POWER_CANDIDATES, power)


def trace(system):
    """Run one non-sequential ray trace with splitting and polarization on."""
    ray_trace = system.Tools.OpenNSCRayTrace()
    ray_trace.SplitNSCRays = True
    ray_trace.ScatterNSCRays = False
    ray_trace.UsePolarization = True
    ray_trace.IgnoreErrors = True
    ray_trace.ClearDetectors(0)
    ray_trace.RunAndWaitForCompletion()
    ray_trace.Close()


def _read_detector_with_nce(system, detector_index, pixels_x, pixels_y):
    """Read detector pixels directly from the NSC editor."""
    editor = system.NCE

    values = []
    for pixel in range(1, pixels_x * pixels_y + 1):
        result = editor.GetDetectorData(detector_index, pixel, 0)
        # pythonnet surfaces the out-parameter either as a tuple or a value.
        values.append(float(result[1] if isinstance(result, tuple) else result))
    return [values[row * pixels_x:(row + 1) * pixels_x]
            for row in range(pixels_y)]


def _read_detector_with_viewer(system, detector_index):
    """Read detector pixels through the DetectorViewer analysis."""
    analysis = None
    try:
        analysis = system.Analyses.New_DetectorViewer()
        analysis_settings = analysis.GetSettings()
        analysis_settings.Detector.SetDetectorNumber(detector_index)
        analysis.ApplyAndWaitForCompletion()
        grid = analysis.GetResults().GetDataGrid(0)
        rows = [[float(grid.Values[row, column]) for column in range(grid.Nx)]
                for row in range(grid.Ny)]
        return rows
    finally:
        try:
            analysis.Close()
        except Exception:  # noqa: BLE001
            pass


def read_detector(system, detector_index, pixels_x, pixels_y):
    """Return the detector grid as rows, plus the route used."""
    try:
        rows = _read_detector_with_viewer(system, detector_index)
        return rows, "DetectorViewer.GetDataGrid"
    except Exception as viewer_error:                 # noqa: BLE001
        try:
            rows = _read_detector_with_nce(system, detector_index, pixels_x,
                                           pixels_y)
            return rows, "NCE.GetDetectorData"
        except Exception as nce_error:                # noqa: BLE001
            raise RuntimeError(
                f"Could not read detector {detector_index}. "
                f"DetectorViewer failed with {viewer_error!r}; "
                f"GetDetectorData failed with {nce_error!r}.")


def _write_csv_rows(csv_path, rows):
    """Write one detector grid to CSV with fixed numeric formatting."""
    with open(csv_path, "w") as handle:
        for row in rows:
            handle.write(",".join(format(value, CSV_FLOAT_FORMAT)
                                  for value in row) + "\n")


def _write_summary(summary_path, summary):
    """Write the sweep summary file with one row per active source."""
    with open(summary_path, "w") as handle:
        handle.write("label,total_power,dir_x,dir_y,dir_z\n")
        for label, total, direction in summary:
            handle.write(f"{label},{format(total, CSV_FLOAT_FORMAT)},{direction[0]:.6f},"
                         f"{direction[1]:.6f},{direction[2]:.6f}\n")


def _load_sweep_inputs(prescription_path):
    """Load the prescription JSON used by the sweep runner."""
    with open(prescription_path) as handle:
        return json.load(handle)


def _detector_label(detector):
    """Return a filesystem-friendly label for one detector."""
    label = detector.get("comment", f"detector_{detector['index']}")
    return label.replace(" ", "_")


def _detector_output_directory(output_directory, detector):
    """Return the directory that holds one detector's sweep results."""
    return os.path.join(output_directory, _detector_label(detector))


def _output_csv_path(output_directory, label):
    """Return the detector CSV path for one source label."""
    return os.path.join(output_directory, PUPIL_CSV_TEMPLATE.format(label=label))


def _record_source_result(summary, source, rows):
    """Compute and store the sweep summary for one source."""
    total = sum(sum(row) for row in rows)
    summary.append((source.get("label", f"source_{source['index']}"),
                    total, source["intended_direction"]))
    return total


def _run_source_sweep(system, sources, detector, output_directory):
    """Trace each source independently and write one detector's output."""
    detector_index = detector["index"]
    pixels_x = detector["data"]["pixels_x"]
    pixels_y = detector["data"]["pixels_y"]
    detector_output_directory = _detector_output_directory(
        output_directory, detector)
    os.makedirs(detector_output_directory, exist_ok=True)

    summary = []
    for source in sources:
        label = source.get("label", f"source_{source['index']}")
        set_only_active_source(system.NCE, sources, source["index"])
        trace(system)
        rows, route = read_detector(system, detector_index, pixels_x, pixels_y)

        csv_path = _output_csv_path(detector_output_directory, label)
        _write_csv_rows(csv_path, rows)

        total = _record_source_result(summary, source, rows)
        print(f"{label}: total {total:.6e}  →  {csv_path}  [{route}]")

    _finalize_sweep(detector_output_directory, summary)


def _finalize_sweep(output_directory, summary):
    """Write the summary CSV and report its location."""
    summary_path = os.path.join(output_directory, SUMMARY_FILENAME)
    _write_summary(summary_path, summary)
    print(f"\nSummary: {summary_path}")


