"""Generate the ZOS-API scripts that build and run the model in OpticStudio.

Two scripts are emitted:

``build_zemax_model.py``
    Reads ``prescription.json`` and constructs the non-sequential system object
    by object, then saves a ``.ZMX``.
``run_fov_sweep.py``
    Opens that ``.ZMX``, enables one projector source at a time, traces, and
    writes detector CSVs — one file per FOV direction and detector, ready to
    compare against Apollo14's own responses.

Both run on the Windows machine with OpticStudio; neither imports apollo14.

Everything version-specific is resolved at runtime rather than hard-coded: ZOS-API
enum members and object-data properties are looked up by name from a candidate
list, and every step that could fail goes through a ``configure`` wrapper that
records the failure and carries on. The scripts therefore build as much of the
model as the installed OpticStudio allows and finish by printing exactly which
settings need setting by hand — instead of dying on the first renamed property.
"""

